DROP TABLE IF EXISTS prijave_edukacije;
DROP TABLE IF EXISTS edukacije;
DROP TABLE IF EXISTS platne_liste;
DROP TABLE IF EXISTS zahtjevi;
DROP TABLE IF EXISTS zaposlenici;
DROP TABLE IF EXISTS postavke;
DROP TABLE IF EXISTS reset_tokeni;
DROP TABLE IF EXISTS korisnici;

CREATE TABLE korisnici (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    email         VARCHAR(120),
    ime           VARCHAR(60),
    prezime       VARCHAR(60),
    uloga         VARCHAR(20)  NOT NULL,
    oib           VARCHAR(11)
);

CREATE TABLE reset_tokeni (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    token      VARCHAR(128) NOT NULL,
    istjece    TIMESTAMP,
    iskoristen BOOLEAN      DEFAULT FALSE NOT NULL
);

CREATE TABLE postavke (
    username   VARCHAR(50) PRIMARY KEY,
    podsjetnik BOOLEAN     NOT NULL,
    sati_prije INT         NOT NULL,
    kanal      VARCHAR(20) NOT NULL
);

CREATE TABLE zaposlenici (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime     VARCHAR(60)  NOT NULL,
    prezime VARCHAR(60)  NOT NULL,
    odjel   VARCHAR(80)  NOT NULL,
    email   VARCHAR(120) NOT NULL
);

-- Zahtjevi za godišnji odmor (razdoblje datum_od – datum_do).
CREATE TABLE zahtjevi (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zaposlenik VARCHAR(50)  NOT NULL,
    datum_od   DATE         NOT NULL,
    datum_do   DATE         NOT NULL,
    razlog     VARCHAR(500) NOT NULL,
    oib        VARCHAR(11),
    status     VARCHAR(20)  NOT NULL,
    kreirano   TIMESTAMP    NOT NULL
);

CREATE TABLE platne_liste (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zaposlenik VARCHAR(50)  NOT NULL,
    razdoblje  VARCHAR(7)   NOT NULL,
    datoteka   VARCHAR(200) NOT NULL
);

CREATE TABLE edukacije (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv       VARCHAR(200) NOT NULL,
    datum       DATE         NOT NULL,
    kapacitet   INT          NOT NULL,
    prijavljeno INT          DEFAULT 0 NOT NULL
);

CREATE TABLE prijave_edukacije (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edukacija_id BIGINT      NOT NULL REFERENCES edukacije (id),
    zaposlenik   VARCHAR(50) NOT NULL,
    kreirano     TIMESTAMP   NOT NULL,
    oznaka_lms   VARCHAR(40)
);
